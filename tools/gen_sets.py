"""(1.5.0, the user's, 2026-11-23) The ready-made sets the FM-1 comes with: stored once, at the first start of 1.5.0,
into the first empty set slots (project.c's first_sets). Their bytes as sets/ has them (what the Sets page would send),
checked as a SET by the Python twin of the container.

    gen_sets.py SETS_DIR build/gen/first_sets.h

The sets, in their order (Set 1, then 2): FIRST below. A file missing, or one that doesn't read as a set: the build
fails.
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import dub1_container as D  # noqa: E402

FIRST = ["winter-set.dub1", "four-to-five.dub1"]
MAX = 16128                     # plat.h's PLAT_FS_MAX: a frame's payload


def main(sets_dir, header):
    arrays, names, total = [], [], 0
    for i, fn in enumerate(FIRST):
        f = Path(sets_dir) / fn
        if not f.is_file():
            raise SystemExit(f"gen_sets: {f} missing (the sets the FM-1 comes with: tools/make_sets.sh makes them)")
        b = f.read_bytes()
        try:
            c = D.parse(b)
        except D.Refused as e:
            raise SystemExit(f"gen_sets: {f} doesn't read ({e})")
        h = c["header"]
        meta = [ch for ch in c["chunks"] if ch["id"] == b"META"]
        if h["kind"] != 2 or not 1 <= h["npieces"] <= 8 or len(b) > MAX or not meta:
            raise SystemExit(f"gen_sets: {f} is not a set of 1 to 8 pieces within a frame")
        names.append(D.name(meta[0]["name"]))
        rows = ",\n".join("    " + ",".join("0x%02x" % x for x in b[j:j + 16]) for j in range(0, len(b), 16))
        arrays.append(f"static const uint8_t first_set{i}[{len(b)}] = {{   /* {fn}: \"{names[-1]}\", "
                      f"{h['npieces']} pieces */\n{rows}\n}};\n")
        total += len(b)
    h = (f"/* generated by gen_sets.py from sets/ ({', '.join(FIRST)}): the sets the FM-1 comes with, stored once at\n"
         f" * the first start of 1.5.0 (project.c's first_sets). Do not edit. */\n"
         f"#define FIRST_SETS_N {len(FIRST)}u\n" + "".join(arrays) +
         "static const uint8_t *const first_set[FIRST_SETS_N] = {" + ", ".join(f"first_set{i}" for i in range(len(FIRST))) + "};\n"
         "static const uint16_t first_set_len[FIRST_SETS_N] = {" + ", ".join(f"sizeof first_set{i}" for i in range(len(FIRST))) + "};\n")
    Path(header).parent.mkdir(parents=True, exist_ok=True)
    if not Path(header).exists() or Path(header).read_text() != h:
        Path(header).write_text(h)
    print(f"first sets: {', '.join(names)} ({total} B) -> {header}")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        raise SystemExit(__doc__)
    main(*sys.argv[1:])
